# ไม่นับ "ผ่อนบ้าน" เพราะยอดผ่อนรวมเงินต้น ไม่ใช่แค่ดอกเบี้ย
# ไม่นับ "ทำบุญ" เพราะทำบุญหลายแบบไม่มีหลักฐานที่นำไปลดหย่อนได้
# ไม่นับ "มูลนิธิ" เพราะเป็นชื่อผู้รับ ไม่ได้บอกว่ายอดนั้นเป็นเงินบริจาค

# ดอกเบี้ยที่ลดหย่อนได้ต้องเป็นเงินกู้เพื่อที่อยู่อาศัย "ดอกเบี้ยเงินกู้รถ" จึงไม่นับ
# รับเฉพาะคำเชื่อมที่รู้จัก ไม่ใช้ "อะไรก็ได้จนเจอบ้าน" เพราะ "ดอกเบี้ยรถ ประกันบ้าน" จะกลายเป็นดอกเบี้ยบ้านทั้งก้อน
# คำเชื่อมอื่น (เช่น สินเชื่อ) จะไม่นับ ต้องเพิ่มพร้อมหลักฐาน
_HOME_LOAN_INTEREST = r"ดอกเบี้ย(?:เงิน)?(?:กู้)?(?:ยืม)?(?:เพื่อ)?(?:ซื้อ)?(?:บ้าน|ที่อยู่อาศัย)"

# ที่ตำแหน่งเดียวกัน re ลองทางเลือกตามลำดับ จึงเรียงคำยาวก่อน ("ประกันสุขภาพ" ต้องได้ก่อน "ประกัน")
# ดอกเบี้ยบ้านอยู่หน้าสุดได้เพราะไม่มีคำอื่นขึ้นต้นด้วย "ดอกเบี้ย"
_TERM_PATTERN = re.compile(
    "|".join([f"(?P<home_loan>{_HOME_LOAN_INTEREST})"]
             + [re.escape(term) for term in sorted(TERMS, key=len, reverse=True)])
)


def normalize(text):
    """ปรับข้อความก่อนเทียบคำ: เลขไทย → อารบิก, รวม ํ + า, ตัวพิมพ์เล็ก, ตัดช่องว่างทั้งหมด, ตัดจุลภาค

    ตัดช่องว่างเพราะผู้ใช้พิมพ์ "Thai ESG" หรือ "ประกัน สุขภาพ" ได้ · ตัดจุลภาคให้ "5,000" เป็น "5000"
    """
    return _WHITESPACE.sub("", normalize_thai_text(text).lower()).replace(",", "")


def find_terms(text):
    """คำที่เจอในข้อความเรียงตามลำดับ เป็น list ของ (ตำแหน่ง, parameter หรือ None)

    ตำแหน่งนับในข้อความหลัง normalize ไม่ใช่ข้อความเดิม
    """
    return [
        (match.start(), "home_loan_interest" if match.group("home_loan") else TERMS[match.group()])
        for match in _TERM_PATTERN.finditer(normalize(text))
    ]
